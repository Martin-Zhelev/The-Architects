#!/usr/bin/env python3
"""Draws the Labyrinth icon once and writes it everywhere it is needed, so the
.exe icon (Explorer, taskbar) and the window icon (title bar, volume mixer)
are the same picture:

  assets/icon.png          256x256 preview
  assets/icon.ico          16-256 px, used by src/app/labyrinth.rc for the .exe
  src/app/embedded_icon.h  the 256x256 PNG as bytes, used for the window icon

Run from the project root:  python3 tools/make_icon.py
"""
import io
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PINK = (255, 50, 210, 255)
CYAN = (40, 230, 255, 255)
GOLD = (255, 230, 80, 255)
BACK = (20, 10, 40, 255)


def draw(size):
    """The art is drawn at 4x and scaled down for smooth edges."""
    big = size * 4
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(image)
    s = big / 64.0  # design grid: 64 x 64
    d.rounded_rectangle([1 * s, 1 * s, 63 * s, 63 * s], radius=12 * s, fill=BACK)
    for ring in range(4):
        r = (26 - ring * 6) * s
        width = max(1, int(round(2.4 * s)))
        colour = PINK if ring % 2 == 0 else CYAN
        d.rectangle([32 * s - r, 32 * s - r, 32 * s + r, 32 * s + r], outline=colour, width=width)
    # gaps in the rings make it read as a maze
    for ring, side in ((0, "top"), (1, "right"), (2, "bottom"), (3, "left")):
        r = (26 - ring * 6) * s
        g = 3.2 * s
        if side == "top":
            d.rectangle([32 * s - g, 32 * s - r - 2 * s, 32 * s + g, 32 * s - r + 2 * s], fill=BACK)
        elif side == "right":
            d.rectangle([32 * s + r - 2 * s, 32 * s - g, 32 * s + r + 2 * s, 32 * s + g], fill=BACK)
        elif side == "bottom":
            d.rectangle([32 * s - g, 32 * s + r - 2 * s, 32 * s + g, 32 * s + r + 2 * s], fill=BACK)
        else:
            d.rectangle([32 * s - r - 2 * s, 32 * s - g, 32 * s - r + 2 * s, 32 * s + g], fill=BACK)
    d.ellipse([28 * s, 28 * s, 36 * s, 36 * s], fill=GOLD)
    return image.resize((size, size), Image.LANCZOS)


def main():
    assets = os.path.join(ROOT, "assets")
    os.makedirs(assets, exist_ok=True)
    draw(256).save(os.path.join(assets, "icon.png"))
    sizes = [16, 24, 32, 48, 64, 128, 256]
    draw(256).save(os.path.join(assets, "icon.ico"), sizes=[(n, n) for n in sizes])

    buffer = io.BytesIO()
    draw(256).save(buffer, format="PNG")
    data = buffer.getvalue()
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    header = (
        "// embedded_icon.h - generated by tools/make_icon.py, do not edit.\n"
        "// The window icon; the same art is in assets/icon.ico for the .exe.\n"
        "#ifndef EMBEDDED_ICON_H\n#define EMBEDDED_ICON_H\n\n"
        "static const unsigned char ICON_PNG_DATA[] = {\n" + "\n".join(lines) + "\n};\n"
        "static const int ICON_PNG_SIZE = %d;\n\n#endif // EMBEDDED_ICON_H\n" % len(data)
    )
    with open(os.path.join(ROOT, "src", "app", "embedded_icon.h"), "w") as out:
        out.write(header)
    print("icon written:", len(data), "bytes")


if __name__ == "__main__":
    main()
